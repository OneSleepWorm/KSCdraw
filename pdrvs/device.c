/**
 * @file    device.c
 * @note    STM32F103C8 外设设备注册表
 * 
 * ============================================================
 * 基本信息
 * ============================================================
 * 依赖:    无 (仅 REGISTER_DEVICE 宏展开)
 * 平台:    STM32 (__USE_STM32__)
 * 
 * ============================================================
 * 用途
 * ============================================================
 * 声明硬件外设实例，供总线框架 (dd.h) 的设备匹配使用。
 * 每个 REGISTER_DEVICE 声明一个外设，包括寄存器基址和
 * RCC 时钟使能地址/位。驱动通过 device_dependency 字符串
 * 匹配这些设备名。
 * 
 * ============================================================
 * 设备列表
 * ============================================================
 * 名称     | 基址       | RCC 地址       | RCC 位
 * ---------+------------+----------------+----------
 * sys      | 0          | —              | —
 * rcc      | 0x40021000 | —              | —
 * flash    | 0x40022000 | —              | —
 * tim1     | 0x40012C00 | 0x40021018(APB2)| bit 11
 * tim2     | 0x40000000 | 0x4002101C(APB1)| bit 0
 * tim3     | 0x40000400 | 0x4002101C(APB1)| bit 1
 * tim4     | 0x40000800 | 0x4002101C(APB1)| bit 2
 * spi1     | 0x40013000 | 0x40021018(APB2)| bit 12
 * spi2     | 0x40003800 | 0x4002101C(APB1)| bit 14
 * uart1    | 0x40013800 | 0x40021018(APB2)| bit 14
 * uart2    | 0x40004400 | 0x4002101C(APB1)| bit 17
 * uart3    | 0x40004800 | 0x4002101C(APB1)| bit 18
 * i2c1     | 0x40005400 | 0x4002101C(APB1)| bit 21
 * i2c2     | 0x40005800 | 0x4002101C(APB1)| bit 22
 * dma1     | 0x40020000 | 0x40021014(AHB) | bit 0
 * gpioa    | 0x40010800 | 0x40021018(APB2)| bit 2
 * gpiob    | 0x40010C00 | 0x40021018(APB2)| bit 3
 * gpioc    | 0x40011000 | 0x40021018(APB2)| bit 4
 * 
 * ============================================================
 * 注意事项
 * ============================================================
 * 1. RCC 由总线 bus_getdriver 自动使能，设备本身不操作 RCC
 * 2. rcc_addr=0 且 rcc_bit=0 的设备不会触发时钟使能
 * 3. 新增外设需在此文件添加 REGISTER_DEVICE
 * 4. 设备名必须与驱动 dep 字符串精确匹配或前缀匹配
 */

